def extract_question_types(entries):
    """Identify recurring question patterns from mark schemes."""
    patterns = Counter()
    for entry in entries:
        answer = entry.get('answer', '').lower()
        entry_type = entry.get('type', 'short')
        marks = entry.get('marks', 1)

        if any(w in answer for w in ['describe', 'explain', 'suggest', 'discuss']):
            patterns['Extended writing (describe/explain/suggest)'] += 1
        elif any(w in answer for w in ['calculate', 'work out', 'determine']):
            patterns['Calculation question'] += 1
        elif any(w in answer for w in ['draw', 'label', 'sketch', 'complete the']):
            patterns['Diagram/labelling task'] += 1
        elif any(w in answer for w in ['tick', 'box', 'circle']):
            patterns['Multiple choice / tick-box'] += 1
        elif any(w in answer for w in ['state', 'give', 'name', 'identify', 'write']):
            patterns['Short recall (state/give/name)'] += 1
        elif entry_type == 'long' or marks >= 3:
            patterns['Extended writing (describe/explain/suggest)'] += 1
        else:
            patterns['Short recall (state/give/name)'] += 1

    return [p for p, c in patterns.most_common(5) if c >= 1]


def extract_paper_sources(entries):
    """List the most relevant past paper sources for a topic."""
    papers = defaultdict(list)
    for entry in entries:
        paper = entry.get('paper', '')
        code = entry.get('code', '')
        session = entry.get('session', '')
        q_num = entry.get('qNum', '')
        label = entry.get('label', '')
        marks = entry.get('marks', 0)

        key = f"{code} {session}"
        papers[key].append(f"Q{q_num}{label} ({marks}m)")

    sources = []
    for paper_key, questions in sorted(papers.items()):
        q_summary = ', '.join(questions[:3])
        if len(questions) > 3:
            q_summary += f' (+{len(questions)-3} more)'
        sources.append(f"- {paper_key}: {q_summary}")

    return sources[:12]


