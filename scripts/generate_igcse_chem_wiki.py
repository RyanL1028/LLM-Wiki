    exam_json = ROOT.parent / "tmp" / "chem-exam-data.json"

    # Also try /tmp/
    if not content_json.exists():
        content_json = Path("/tmp/chem-content-db.json")
    if not exam_json.exists():
        exam_json = Path("/tmp/chem-exam-data.json")

    with open(content_json) as f:
        db = json.load(f)
    with open(exam_json) as f:
        exams = json.load(f)

    entries = []
    for topic, qlist in db.items():
        if topic.startswith('_'):
            continue
        if isinstance(qlist, list):
            for item in qlist:
                if isinstance(item, dict):
                    item['_topic'] = topic
                    entries.append(item)

    print(f"  Loaded {len(entries)} Q+A entries from {len(exams)} papers")
    return entries, exams


