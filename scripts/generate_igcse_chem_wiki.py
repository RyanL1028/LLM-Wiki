# ── Classification ────────────────────────────────────────────────

def classify_entry(entry):
    """Classify a single Q+A entry to one or more topics based on keyword matching."""
    answer = entry.get('answer', '')
    question = entry.get('questionText', '')
    text = (answer + ' ' + question).lower()

    scores = {}
    for topic_name, topic_info in TOPICS.items():
        score = 0
        for pattern in topic_info['keywords']:
            if re.search(pattern, text, re.IGNORECASE):
                score += 1
        if score > 0:
            scores[topic_name] = score

    if not scores:
        return ['Mixed Chemistry']

    # Require at least 3 keyword matches to classify (stricter to avoid cross-contamination)
    qualified = [t for t, s in scores.items() if s >= 3]
    if qualified:
        return qualified
    elif scores:
        best = max(scores, key=scores.get)
        if scores[best] >= 2:
            return [best]
    return ['Mixed Chemistry']


def extract_key_facts(entries):
    """Extract cleaned, study-ready facts from mark scheme answers."""
    facts = []
    seen = set()

    for entry in entries:
        answer = entry.get('answer', '').strip()
        if not answer or len(answer) < 3:
            continue

        # Clean mark scheme formatting
        cleaned = answer
        cleaned = re.sub(r'\s*\(\d+\)', '', cleaned)  # Remove (1) (2) marks
        cleaned = re.sub(r'^\d+\s*', '', cleaned)  # Remove leading numbers
        cleaned = re.sub(r'one mark each for any \d+ of:?\s*', '', cleaned)
        cleaned = re.sub(r'(?:IF|if) \d+ marks? not scored.*', '', cleaned)
        cleaned = re.sub(r'max\s*\d+\s*marks?', '', cleaned)
        cleaned = re.sub(r'\baward\s+\d+\s+mark', '', cleaned)
        cleaned = cleaned.strip(' ;,•')

        # Split multi-point answers
        points = re.split(r'\s*[;•]\s*|\s*\d+\s*[.)]\s*', cleaned)
        for point in points:
            point = point.strip()
            if len(point) < 10 or len(point) > 200:
                continue
            # Deduplicate (case-insensitive)
            key = point.lower()
            if key not in seen:
                seen.add(key)
                facts.append(point)

    return facts[:30]  # Limit per topic


def extract_equations(entries):
    """Find chemical equations and reactions from mark scheme answers."""
    equations = set()
    for entry in entries:
        answer = entry.get('answer', '')
        # Find chemical formulas
        formulas = re.findall(r'[A-Z][a-z]?\d*(?:\([A-Z][a-z]?\d*\))?\d*[→+]+[A-Z][a-z]?\d*', answer)
        for f in formulas:
            if len(f) > 8:
                equations.add(f)
    return sorted(equations)[:10]


